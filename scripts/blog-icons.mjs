// Writes src/site/blogIcons.ts: the inner SVG markup of the Lucide icons the blog's Markdown can
// use as {{name}} (see src/site/markdown.ts), copied from the lucide-react package so the icons
// match the ones the site's components draw. Run it after adding a name to ICON_NAMES:
//
//   node scripts/blog-icons.mjs
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

export const ICON_NAMES = [
  "lightbulb", "info", "sparkles", "triangle-alert", "message-circle", "circle-check", "circle-x", "circle-help",
  "check", "x", "ban", "scissors", "image", "file-image", "file-text", "type", "ruler", "eye", "eye-off", "lock",
  "package", "search", "wrench", "layers", "cpu", "table", "paintbrush", "database", "server-off", "globe",
  "binary", "flask-conical", "hand", "gauge", "shield-check", "pen-line", "wand-sparkles", "list", "arrow-right",
  "baseline", "wrap-text", "text-cursor-input", "pilcrow", "cloud-off", "hard-drive", "download", "frame",
  "keyboard", "languages", "mouse-pointer-click", "bug", "history", "italic", "bold", "highlighter", "stamp",
  "puzzle", "scan-text", "microscope", "target", "eraser", "palette", "letter-text", "whole-word",
  "move-horizontal", "scale", "blocks", "zap", "hourglass", "rocket", "book-open", "hammer", "glasses",
  "feather", "quote", "trophy", "milestone", "route", "split", "undo-2", "columns-2", "grid-2x2",
  "square-dashed", "component", "box", "badge-check", "upload", "timer", "flag", "crop", "footprints",
  "compass", "map-pin", "brackets",
];

function attrs(props) {
  return Object.entries(props)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => ` ${key}="${value}"`)
    .join("");
}

const entries = [];
for (const name of ICON_NAMES) {
  const file = path.join(root, "node_modules/lucide-react/dist/esm/icons", `${name}.mjs`);
  // The module imports React through createLucideIcon, so the data object is read out of the
  // source text instead of importing it.
  let source = await readFile(file, "utf8"); // a clear error for a misspelt name
  // An alias module re-exports another icon's file.
  const alias = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs';/.exec(source);
  if (alias) source = await readFile(path.join(path.dirname(file), `${alias[1]}.mjs`), "utf8");
  const literal = /const __iconData = (\{[\s\S]*?\n\});/.exec(source)?.[1];
  if (!literal) throw new Error(`No icon data in ${file}`);
  const data = new Function(`return ${literal}`)();
  const markup = data.node.map(([tag, props]) => `<${tag}${attrs(props)}/>`).join("");
  entries.push(`  "${name}": '${markup}',`);
}

const out = `// Generated by scripts/blog-icons.mjs from lucide-react ${JSON.parse(await readFile(path.join(root, "node_modules/lucide-react/package.json"), "utf8")).version}. Do not edit;
// add a name to ICON_NAMES in that script and run it again.
// Lucide icons, ISC licence: https://lucide.dev/license
// This file imports nothing, so src/data/posts.ts can use it while vite.config.ts loads the posts.
export const ICONS: Record<string, string> = {
${entries.join("\n")}
};

// An icon as inline SVG markup that takes the text colour.
export function iconHtml(name: string, className = "bp-icon"): string {
  const body = ICONS[name];
  if (!body) throw new Error(\`Unknown blog icon "\${name}"; add it to scripts/blog-icons.mjs and rerun it\`);
  return \`<svg class="\${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${body}</svg>\`;
}
`;
await writeFile(path.join(root, "src/site/blogIcons.ts"), out);
console.log(`wrote ${entries.length} icons to src/site/blogIcons.ts`);
